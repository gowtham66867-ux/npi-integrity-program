def npi_check_digit(base9: str) -> str:
    digits = "80840" + base9
    total = 0
    for i, ch in enumerate(reversed(digits)):
        d = int(ch)
        if i % 2 == 0:
            d *= 2
            if d > 9:
                d -= 9
        total += d
    return str((10 - total % 10) % 10)


def mdy(d: date | None) -> str:
    return d.strftime("%m/%d/%Y") if d else ""


def ymd(d: date | None) -> str:
    return d.strftime("%Y%m%d") if d else ""


def month_starts(start: date, end: date):
    d = date(start.year, start.month, 1)
    while d <= end:
        yield d
        d = date(d.year + (d.month // 12), d.month % 12 + 1, 1)


def month_end(d: date) -> date:
    nxt = date(d.year + (d.month // 12), d.month % 12 + 1, 1)
    return nxt - timedelta(days=1)


@dataclass
class Provider:
    npi: str
    entity: str                      # "1" individual, "2" organization
    taxonomy: str
    city: str
    state: str
    zip5: str
    addr1: str
    addr2: str = ""
    last: str = ""
    first: str = ""
    middle: str = ""
    org_name: str = ""
    credential: str = ""
    sex: str = ""
    phone: str = ""
    enum_date: date = date(2010, 1, 1)
    last_update: date = date(2024, 1, 1)
    deact_date: date | None = None
    react_date: date | None = None
    auth_last: str = ""
    auth_first: str = ""
    auth_title: str = ""
    group_npi: str | None = None     # reassigns benefits to this org
    in_ordref: bool = True
    tags: list = field(default_factory=list)

    @property
    def group(self) -> str:
        return TAXONOMY[self.taxonomy][0]

    def nppes_row(self, deactivated_view: bool = False) -> list[str]:
        if deactivated_view:
            # NPPES publishes deactivated NPIs with identity fields blanked.
            row = {c: "" for c in NPPES_COLS}
            row["NPI"] = self.npi
            row["NPI Deactivation Date"] = mdy(self.deact_date)
            row["NPI Deactivation Reason Code"] = "DT" if "retired" in self.tags else ""
            return [row[c] for c in NPPES_COLS]
        return [
            self.npi, self.entity, "", "", self.org_name, self.last, self.first, self.middle, self.credential,
            self.addr1, self.addr2, self.city, self.state, self.zip5 + "0000", self.phone, mdy(self.enum_date),
            mdy(self.last_update), "", mdy(self.deact_date) if self.react_date else "", mdy(self.react_date),
            self.sex, self.auth_last, self.auth_first, self.auth_title, self.taxonomy, "Y",
        ]


class Generator:
    def __init__(self, seed: int = SEED, n_individuals: int = 5200, n_billing: int = 650):
        self.rng = random.Random(seed)
        self.n_individuals = n_individuals
        self.n_billing = n_billing
        self.providers: dict[str, Provider] = {}
        self.used_npis: set[str] = set()
        self.used_addresses: set[str] = set()
        self.claims: list[list] = []
        self.claim_seq = 0
        self.patient_seq = 0
        self.leie_rows: list[dict] = []
        self.sam_rows: list[dict] = []
        self.optout_rows: list[dict] = []
        self.secondary_locations: list[list[str]] = []
        self.address_types: list[list[str]] = []
        self.weekly_changes: dict[date, list[Provider]] = {}
        self.deact_report: list[tuple[str, date]] = []
        self.scenarios: list[dict] = []
        self.decoys: list[dict] = []
        self.billing: list[Provider] = []
        self.no_mup: set[str] = set()
        self.original: dict[str, Provider] = {}
        self.keep_claims: set[str] = set()

    # ----------------------------------------------------------------- helpers
    def new_npi(self) -> str:
        while True:
            base = "1" + "".join(str(self.rng.randint(0, 9)) for _ in range(8))
            npi = base + npi_check_digit(base)
            if npi not in self.used_npis:
                self.used_npis.add(npi)
                return npi

    def pick_city(self) -> str:
        cities = list(CITY_WEIGHTS)
        return self.rng.choices(cities, weights=[CITY_WEIGHTS[c] for c in cities])[0]

    def city_zip(self, city: str) -> str:
        return self.rng.choice(CITIES[city][1])[0]

    def new_address(self, suite: bool | None = None) -> tuple[str, str]:
        while True:
            line1 = f"{self.rng.randint(10, 9899)} {self.rng.choice(STREETS)} {self.rng.choice(SUFFIXES)}"
            if line1 not in self.used_addresses:
                self.used_addresses.add(line1)
                break
        if suite is None:
            suite = self.rng.random() < 0.4
        line2 = f"SUITE {self.rng.randint(100, 950)}" if suite else ""
        return line1, line2

    def phone(self) -> str:
        return f"{self.rng.randint(201, 989)}{self.rng.randint(200, 999)}{self.rng.randint(1000, 9999)}"

    def person_name(self):
        return self.rng.choice(LAST_NAMES), self.rng.choice(FIRST_NAMES), self.rng.choice("ABCDEFGHJKLMNPRSTW")

    def make_individual(self, taxonomy: str | None = None, city: str | None = None, **kw) -> Provider:
        taxonomy = taxonomy or self.rng.choices(list(INDIVIDUAL_TAX_WEIGHTS),
                                                weights=list(INDIVIDUAL_TAX_WEIGHTS.values()))[0]
        city = city or self.pick_city()
        state = CITIES[city][0]
        last, first, middle = self.person_name()
        a1, a2 = self.new_address()
        enum = kw.pop("enum_date", None) or date(2005, 6, 1) + timedelta(days=self.rng.randint(0, 7300))
        p = Provider(npi=kw.pop("npi", None) or self.new_npi(), entity="1", taxonomy=taxonomy, city=city, state=state,
                     zip5=kw.pop("zip5", None) or self.city_zip(city), addr1=kw.pop("addr1", a1),
                     addr2=kw.pop("addr2", a2), last=kw.pop("last", last), first=kw.pop("first", first),
                     middle=kw.pop("middle", middle), credential=CREDENTIALS[TAXONOMY[taxonomy][0]],
                     sex=self.rng.choice("MF"), phone=self.phone(), enum_date=enum,
                     last_update=min(date(2026, 7, 1), enum + timedelta(days=self.rng.randint(30, 3000))), **kw)
        self.providers[p.npi] = p
        return p

    def make_org(self, name: str, taxonomy: str, city: str, auth: tuple[str, str] | None = None, **kw) -> Provider:
        state = CITIES[city][0]
        a1, a2 = self.new_address()
        al, af, _ = self.person_name()
        auth = auth or (al, af)
        p = Provider(npi=self.new_npi(), entity="2", taxonomy=taxonomy, city=city, state=state,
                     zip5=kw.pop("zip5", None) or self.city_zip(city), addr1=kw.pop("addr1", a1),
                     addr2=kw.pop("addr2", a2), org_name=name, phone=self.phone(),
                     enum_date=kw.pop("enum_date", date(2008, 1, 1) + timedelta(days=self.rng.randint(0, 5000))),
                     last_update=date(2025, 3, 1), auth_last=auth[0], auth_first=auth[1],
                     auth_title=kw.pop("auth_title", "ADMINISTRATOR"), in_ordref=False, **kw)
        self.providers[p.npi] = p
        return p

    def new_patient(self) -> str:
        self.patient_seq += 1
        return f"BENE{self.patient_seq:08d}"

    def add_claim(self, svc: date, billing: Provider, rendering: Provider, patient: str, lines, pos="11",
                  svc_zip=None, ordering: Provider | None = None):
        """lines: list of (hcpcs, units)."""
        self.claim_seq += 1
        clm = f"CL-{self.claim_seq:08d}"
        z = svc_zip or rendering.zip5
        for i, (code, units) in enumerate(lines, start=1):
            amt = CODES[code][2] * units * self.rng.uniform(0.92, 1.05)
            self.claims.append([clm, i, f"{clm}-{i}", svc, billing.npi, rendering.npi,
                                ordering.npi if ordering else "", patient, code, units, pos, z, round(amt, 2), "MEDICARE"])

    def workday(self, month: date, lo: int = 1, hi: int | None = None) -> date:
        hi = hi or month_end(month).day
        for _ in range(50):
            d = month.replace(day=self.rng.randint(lo, hi))
            if d.weekday() < 5:
                return d
        return month.replace(day=lo)

    def billing_entity(self, p: Provider) -> Provider:
        return self.providers[p.group_npi] if p.group_npi else p

    # ------------------------------------------------------------- universe
    def build_universe(self):
        rng = self.rng
        individuals = [self.make_individual() for _ in range(self.n_individuals)]

        # Same-specialty group practices: shared address, benefits reassigned to the group.
        pool = individuals[:]
        rng.shuffle(pool)
        i = 0
        while i < int(len(pool) * 0.35):
            size = rng.randint(2, 8)
            members = pool[i:i + size]
            i += size
            lead = members[0]
            # group practices are single-specialty and single-city
            org = self.make_org(f"{lead.last} {TAXONOMY[lead.taxonomy][1].upper()} ASSOCIATES PLLC", "193200000X",
                                lead.city)
            a1, a2 = self.new_address(suite=True)
            for m in members:
                m.taxonomy = lead.taxonomy
                m.credential = CREDENTIALS[m.group]
                m.city, m.state, m.zip5, m.addr1, m.addr2 = org.city, org.state, org.zip5, a1, a2
                m.group_npi = org.npi
            org.addr1, org.addr2 = a1, a2

        # Home health agencies; their certifying physicians are background IM/FM doctors.
        for _ in range(40):
            city = self.pick_city()
            last, _, _ = self.person_name()
            self.make_org(f"{last} HOME HEALTH SERVICES LLC", "251E00000X", city, auth_title="OWNER")

        # Background deactivations among non-billing individuals (retirements etc.).
        for p in rng.sample(individuals, 90):
            p.deact_date = date(2024, 1, 1) + timedelta(days=rng.randint(0, 900))
            p.tags.append("retired")
            if p.deact_date <= date(2026, 9, 14):
                self.deact_report.append((p.npi, p.deact_date))

        # A few individuals are not in the Order & Referring file (not PECOS-approved to order).
        for p in rng.sample(individuals, 120):
            p.in_ordref = False

        # Medicare by Provider covers most practitioners; ~10% do not bill Medicare.
        self.no_mup = {p.npi for p in rng.sample(individuals, len(individuals) // 10)}

        eligible = [p for p in individuals if not p.deact_date and p.in_ordref and p.enum_date < date(2024, 6, 1)]
        self.billing = rng.sample(eligible, self.n_billing)
        for p in self.billing:
            p.tags.append("billing")
            self.init_panel(p)

        # Background NPPES churn: ~60 single address changes and a handful of taxonomy updates.
        weeks = [date(2026, 7, 20) + timedelta(days=7 * k) for k in range(12)]
        self.weeks = weeks
        for p in rng.sample([x for x in individuals if not x.group_npi and not x.deact_date], 60):
            wk = rng.choice(weeks)
            self.remember(p)
            p.addr1, p.addr2 = self.new_address()
            p.last_update = wk - timedelta(days=2)
            self.weekly_changes.setdefault(wk, []).append(self.snapshot(p))

        # Background SAM exclusions (none billing) and LEIE exclusions (mostly non-providers).
        for _ in range(60):
            last, first, middle = self.person_name()
            city = self.pick_city()
            self.sam_rows.append(self.sam_row(first, last, middle, city, date(2021, 1, 1) +
                                              timedelta(days=rng.randint(0, 1900))))
        for _ in range(420):
            last, first, middle = self.person_name()
            city = self.pick_city()
            self.leie_rows.append(self.leie_row(last, first, middle, city,
                                                date(2010, 1, 1) + timedelta(days=rng.randint(0, 6060)),
                                                general=rng.choice(["IND- LIC HC SERV PRO", "NURSING PROFESSION",
                                                                    "OTHER BUSINESS", "PHARMACY"])))

    def snapshot(self, p: Provider) -> Provider:
        from copy import copy
        return copy(p)

    def remember(self, p: Provider):
        """Keep the pre-change state for the July full file before a weekly change mutates p."""
        self.original.setdefault(p.npi, self.snapshot(p))

    def other_city(self, city: str) -> str:
        state = CITIES[city][0]
        return next(c for c, (st, _) in CITIES.items() if st == state and c != city)

    def leie_row(self, last, first, middle, city, excl, npi="0000000000", rein=None, general="IND- LIC HC SERV PRO",
                 busname="", zip5=None, specialty="", excltype="1128a1"):
        state = CITIES[city][0]
        dob = date(1950, 1, 1) + timedelta(days=self.rng.randint(0, 15000))
        a1, _ = self.new_address(suite=False)
        return {"LASTNAME": last, "FIRSTNAME": first, "MIDNAME": middle, "BUSNAME": busname, "GENERAL": general,
                "SPECIALTY": specialty, "UPIN": "", "NPI": npi, "DOB": ymd(dob) if last else "", "ADDRESS": a1,
                "CITY": city, "STATE": state, "ZIP": zip5 or self.city_zip(city), "EXCLTYPE": excltype,
                "EXCLDATE": ymd(excl), "REINDATE": ymd(rein) if rein else "00000000", "WAIVERDATE": "00000000",
                "WVRSTATE": ""}

    def sam_row(self, first, last, middle, city, active, npi=""):
        a1, _ = self.new_address(suite=False)
        return {"Classification": "Individual", "Name": "", "Prefix": "", "First": first, "Middle": middle,
                "Last": last, "Suffix": "", "Address 1": a1, "City": city, "State / Province": CITIES[city][0],
                "Country": "USA", "Zip Code": self.city_zip(city), "Unique Entity ID": "",
                "Exclusion Program": "Reciprocal", "Excluding Agency": "HHS", "CT Code": "Z1",
                "Exclusion Type": "Prohibition/Restriction", "Additional Comments": "",
                "Active Date": mdy(active), "Termination Date": "Indefinite", "Record Status": "",
                "Cross-Reference": "", "SAM Number": f"S4MR{self.rng.randint(100000, 999999)}", "CAGE": "",
                "NPI": npi}

