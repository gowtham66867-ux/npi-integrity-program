    def practice_month(self, p: Provider, month: date, scale: float = 1.0, patients: list[str] | None = None,
                       zip_override: str | None = None, max_day: int | None = None):
        rng = self.rng
        grp = p.group
        bill = self.billing_entity(p)
        if patients is None:
            patients = p._panel
        n = max(0, int(rng.gauss(VISITS_PER_MONTH[grp], VISITS_PER_MONTH[grp] * 0.25) * scale))
        tele_share = 0.3 if grp in ("PSYCH", "PSYCHOLOGIST") else 0.06
        for _ in range(n):
            d = self.workday(month, hi=max_day)
            pt = rng.choice(patients)
            pos = "10" if rng.random() < tele_share else "11"
            new = pt not in p._seen
            p._seen.add(pt)
            lines = self.visit_lines(grp, new)
            self.add_claim(d, bill, p, pt, lines, pos=pos, svc_zip=zip_override)

    def visit_lines(self, grp: str, new: bool):
        rng = self.rng
        pick = lambda opts: rng.choices([c for c, _ in opts], weights=[w for _, w in opts])[0]
        if grp == "PSYCHOLOGIST":
            return [("90791", 1)] if new else [(rng.choice(["90837", "90834", "90834", "90832"]), 1)]
        if grp == "PSYCH":
            if new:
                return [("90791", 1)]
            return [(pick(EM_ESTABLISHED), 1)] + ([("90834", 1)] if rng.random() < 0.3 else [])
        if grp == "PT":
            if new:
                return [("97161", 1)]
            return [("97110", rng.randint(1, 3)), ("97140", 1)] + ([("97530", 1)] if rng.random() < 0.4 else [])
        if grp == "CHIRO":
            return [("98940", 1)]
        lines = [(pick(EM_NEW if new else EM_ESTABLISHED), 1)]
        fam_codes = {"IM": ["36415", "81002", "93000", "90471"], "FM": ["36415", "81002", "90471", "93000"],
                     "NP": ["36415", "81002", "90471"], "PA": ["36415", "20610", "90471"],
                     "CARD": ["93000", "93306", "93350", "93880"], "OBGYN": ["76805", "58300", "57454", "36415"],
                     "NEURO": ["95907", "95886", "95816", "95910"], "ORTHO": ["20610", "73560", "29881"],
                     "DERM": ["11102", "17000", "17110"]}[grp]
        if rng.random() < 0.35:
            lines.append((rng.choice(fam_codes), 1))
        return lines

    def init_panel(self, p: Provider, size: int | None = None):
        p._panel = [self.new_patient() for _ in range(size or self.rng.randint(80, 240))]
        p._seen = set()

    def rpm_program(self, p: Provider, n_patients: int, start_lo: date, start_hi: date, mgmt_prob=0.95,
                    prior_visit=True, ordering: Provider | None = None, end: date = CLAIMS_END):
        """Background-style RPM: each patient is seen, then enrolled; device + management billed monthly."""
        rng = self.rng
        bill = self.billing_entity(p)
        span = (start_hi - start_lo).days
        for _ in range(n_patients):
            pt = rng.choice(p._panel) if prior_visit else self.new_patient()
            start = start_lo + timedelta(days=rng.randint(0, max(span, 1)))
            start = date(start.year, start.month, 1)
            if prior_visit:
                v = start - timedelta(days=rng.randint(5, 40))
                v = self.workday(date(v.year, v.month, 1))
                if v >= CLAIMS_START:
                    self.add_claim(v, bill, p, pt, [(rng.choice(["99213", "99214"]), 1)])
                    p._seen.add(pt)
            months = rng.randint(4, 18)
            for k, m in enumerate(month_starts(start, end)):
                if k >= months:
                    break
                d = self.workday(m, lo=18, hi=28)
                lines = ([("99453", 1)] if k == 0 else []) + [("99454", 1)]
                if rng.random() < mgmt_prob:
                    lines.append(("99457", 1))
                    if rng.random() < 0.4:
                        lines.append(("99458", 1))
                self.add_claim(d, bill, p, pt, lines, ordering=ordering or p)

    def background_claims(self):
        rng = self.rng
        for p in self.billing:
            if "special" in p.tags:
                continue
            for m in month_starts(CLAIMS_START, CLAIMS_END):
                self.practice_month(p, m)
            if p.group in ("IM", "FM", "NP", "CARD") and "planted" not in p.tags and rng.random() < 0.25:
                p.tags.append("rpm")
                self.rpm_program(p, rng.randint(8, 35), date(2025, 3, 1), date(2026, 8, 1))
        # Home health agencies bill skilled-nursing visits certified by local physicians.
        clean = lambda p: not {"planted", "decoy", "special"} & set(p.tags)
        certifiers = [p for p in self.billing if p.group in ("IM", "FM") and clean(p)]
        for org in [p for p in self.providers.values() if p.taxonomy == "251E00000X" and "special" not in p.tags]:
            local = [c for c in certifiers if c.city == org.city] or certifiers
            docs = rng.sample(local, min(3, len(local)))
            for _ in range(rng.randint(15, 40)):
                pt = self.new_patient()
                cert = rng.choice(docs)
                start = date(2025, 1, 1) + timedelta(days=rng.randint(0, 560))
                for k in range(rng.randint(3, 10)):
                    d = start + timedelta(days=7 * k)
                    if d > CLAIMS_END:
                        break
                    self.add_claim(d, org, org, pt, [(rng.choice(["G0299", "G0299", "G0151"]), 1)], pos="12",
                                   ordering=cert)

